test('theme disclosure supports keyboard toggling and keeps every existing setting', async () => {
  const { page, context } = await openComic(browser)
  try {
    await page.locator('[data-tab="settings"]').click()
    assert.equal(await page.locator('details#ten-theme-settings').count(), 1)
    const summary = page.locator('#ten-theme-settings > summary')
    await summary.focus()
    await summary.press('Enter')
    assert.equal(await page.locator('#ten-theme-settings [data-theme-choice]').count(), 6)
    assert.equal(await page.locator('#ten-theme-settings [data-appearance-axis]').count(), 9)
    assert.deepEqual(await page.locator('#ten-theme-settings .ten-settings-section > .ten-card-title').allTextContents(), ['预设选择', '外观调整', '界面设置'])
    await page.locator('[data-theme-choice="cloud"]').click()
    await page.locator('[data-appearance-axis="density"][data-appearance-value="compact"]').click()
    await page.locator('[data-appearance-axis="shape"][data-appearance-value="sharp"]').click()
    await page.locator('[data-appearance-axis="motion"][data-appearance-value="calm"]').click()
    await page.locator('#ten-hotkey').fill('M')
    await page.locator('#ten-hotkey').press('Tab')
    await page.locator('#ten-auto-open').uncheck()
    await page.locator('#ten-scale').press('ArrowRight')
    await page.locator('[data-effect-level="2"]').click()
    await summary.press('Space')
    assert.equal(await page.locator('#ten-theme-settings').evaluate(element => element.open), false)
    await summary.press('Space')
    assert.equal(await page.locator('#ten-hotkey').inputValue(), 'M')
    const settings = await page.evaluate(() => ({ theme: window.__gmValues.themePreset, axes: window.__gmValues.appearanceAxes, ui: window.__gmValues.appLoadDefault, effects: window.__gmValues.effectLevel }))
    assert.equal(settings.theme, 'cloud')
    assert.deepEqual(settings.axes, { density: 'compact', shape: 'sharp', motion: 'calm' })
    assert.equal(settings.ui.loadHotKey, 'M')
    assert.equal(settings.ui.isShowUI, false)
    assert.equal(settings.ui.rightSize, 101)
    assert.equal(settings.effects, 2)
    await page.locator('#ten-rule-editor-card > summary').press('Enter')
    assert.equal(await page.locator('#ten-rule-name').isVisible(), true)
    await page.locator('#ten-rule-editor-card > summary').press('Space')
    assert.equal(await page.locator('#ten-rule-name').isVisible(), false)
  } finally { await context.close() }
})

