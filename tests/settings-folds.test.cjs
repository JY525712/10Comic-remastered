test('expanded custom rules keep the advanced mobile drawer usable', async () => {
  const { page, context, errors } = await openComic(browser, { viewport: { width: 390, height: 844 } })
  try {
    await page.locator('[data-tab="settings"]').click()
    assert.equal(await page.locator('details#ten-rule-editor-card').count(), 1)
    await page.locator('#ten-rule-editor-card > summary').click()
    await page.locator('#ten-rule-advanced > summary').click()
    await page.locator('#ten-mobile-drawer.is-open').waitFor()
    assert.equal(await page.locator('#ten-rule-getimgs').isVisible(), true)
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('#ten-rule-editor-card').evaluate(element => element.open), true)
    assert.equal(await page.locator('#ten-rule-advanced').evaluate(element => element.open), false)
    assert.equal(await page.evaluate(() => document.activeElement.closest('details').id), 'ten-rule-advanced')
    await page.locator('#ten-rule-editor-card > summary').click()
    assert.equal(await page.locator('#ten-rule-name').isVisible(), false)
    assert.deepEqual(errors, [])
  } finally { await context.close() }
})
